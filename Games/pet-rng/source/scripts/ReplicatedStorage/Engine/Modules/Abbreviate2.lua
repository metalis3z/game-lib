module.abbreviate = function(number)
	for i =1, #abvs do
		if number < 10 ^ (i * 3) then
			if abvs[i] == "∞" then
				return "∞"
			else
				return math.floor(number / ((10 ^ ((i-1) * 3)) / 100)) / (100)..abvs[i]
			end
		elseif tostring(number) == "inf" then
			return "∞"
		end
	end
end
return module

