function Gamepasses.Owns(gamepassId)
	--- Get gamepasses owned by player
	local playerStats = _L.Stats.Get(true) --- cached results
	local gamepassesOwned = playerStats.Gamepasses

	--- Search for gamepass
	for _, ownedGamepassId in ipairs(gamepassesOwned) do
		if ownedGamepassId == gamepassId then
			return true
		end
	end

	--
	return false
end


function Gamepasses.GetOwned()
	--- Get gamepasses owned by player
	local playerStats = _L.Stats.Get(true) --- cached results
	local gamepassesOwned = playerStats.Gamepasses

	--
	return gamepassesOwned
end


