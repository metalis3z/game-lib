--- Internal function that handles caching/retrieving initial property values
function GUIFX.CacheProperty(gui, property)
	if gui then
		--- Check & add cache
		if cachedProperties[gui] == nil then
			cachedProperties[gui] = {}
		end

		--- Check & add property cache
		if cachedProperties[gui][property]  == nil then
			cachedProperties[gui][property] = gui[property]
		end

		--
		return cachedProperties[gui][property]
	end
end


--- Internal function that returns a screengui that can be used for GUI FX
function GUIFX.GetHolder()
	if guiHolder == nil then
		guiHolder = Instance.new("ScreenGui")
		guiHolder.Name = "GUIFX Holder"
		guiHolder.DisplayOrder = 999
		guiHolder.Parent = playerGui
	end

	--
	return guiHolder
end


