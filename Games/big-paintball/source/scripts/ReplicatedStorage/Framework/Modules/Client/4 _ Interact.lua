	_L.Interact
	===========
	Create a interactable button in 3D space for interacting with objects. Appears when player is a specified magnitude in range
	from the object in question. Unless defined, the closest button in range will be shown instead of all at once. Returns an 
	event which is fired whenever a player presses it. Cross compatible with all platforms - PC, Mobile, Xbox.
	===========
		\\\ Returns an event & function to cancel (in that order)
		Interact.Add(
			position/part,						<-- |REQ|	Vector3/CFrame or Instance for button position
			minDistance,						<--			Minimum distance for button to appear	[defaults to: 10]
		)
		
		
		/// EXAMPLE ///
		Interact.Add(Vector3.new(0.5, 0.5, 0.5), 10):Connect(function()
			--- Clicked
		end)
	===========
