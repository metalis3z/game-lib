function Interact.Add(host, interactMinDistance)
	--- Debug
	if not host then
		_L.Print("First param is nil", true)
		return
	end

	--- Variables
	interactMinDistance = interactMinDistance or 10
	local inputEvents = {}
	local billboardVisible = false
	local billboard
	local billboardId = _L.Functions.GenerateUID()
	local closing = false
	local clickDeb = false
	local debrisHost = false

	--- Create the host part for button
	if typeof(host) ~= "Instance" then
		local interactPosition = host
		host = _L.Functions.CreateParticleHost(interactPosition)
		debrisHost = true
	end

	--- Create the button event
	local event = Instance.new("BindableEvent")
	event.Name = "Activated"
	event.Parent = host

	--- Add to list of billboards
	billboards[billboardId] = {
		id = billboardId,
		host = host,
		lastDist = 0,
		lastCheck = 0,
		maxDist = interactMinDistance,
	}

	--- Button activated!
	local function ButtonActivate()
		event:Fire()
	end

	--- Button pressed down!
	local function ButtonDownFX()
		if not clickDeb then
			clickDeb = true
			--
			_L.Audio.Play(pressDownSound, script, 1, 1)
			billboard.Button.Back.ImageColor3 = Color3.new(0.85, 0.85, 0.85)
			_L.Functions.FastTween(billboard.Button.Back, {Size = UDim2.new(0.65, 0, 0.65, 0)}, {0.5, Enum.EasingStyle.Elastic, Enum.EasingDirection.Out})
			--
			clickDeb = false
		end
	end

	--- Button pressed up!
	local function ButtonUpFX()
		if not clickDeb then
			clickDeb = true
			--
			_L.Audio.Play(pressUpSound, script, 1, 1)
			if billboard:FindFirstChild("Button") then
				billboard.Button.Back.ImageColor3 = Color3.new(1, 1, 1)
				_L.Functions.FastTween(billboard.Button.Back, {Size = UDim2.new(0.8, 0, 0.8, 0)}, {0.5, Enum.EasingStyle.Elastic, Enum.EasingDirection.Out})
			end
			--
			clickDeb = false
		end
	end

	--- Host the events for the button
	local function Events()
		if billboard then
			local function EnabledCheck()
				if (not _L.Variables.Typing) and (not _L.Variables.MessageOpen) and billboards[billboardId] then
					return true
				end
			end

			--- XBOX & Mobile
			inputEvents[#inputEvents + 1] = _L.Services.UserInputService.InputBegan:Connect(function(input)
				if EnabledCheck() then
					if input.KeyCode == Enum.KeyCode.ButtonX or input.KeyCode == Enum.KeyCode.E then
						ButtonDownFX()
					end
				end
			end)

			inputEvents[#inputEvents + 1] = _L.Services.UserInputService.InputEnded:Connect(function(input)
				if EnabledCheck() then
					if input.KeyCode == Enum.KeyCode.ButtonX or input.KeyCode == Enum.KeyCode.E then
						ButtonUpFX()
						ButtonActivate()
					end
				end
			end)

			--- PC
			inputEvents[#inputEvents + 1] = billboard.Button.MouseButton1Down:Connect(function()
				if EnabledCheck() then
					ButtonDownFX()
				end
			end)

			inputEvents[#inputEvents + 1] = billboard.Button.MouseButton1Up:Connect(function()
				if EnabledCheck() then
					ButtonActivate()
					ButtonUpFX()
				end
			end)
		end
	end

	--- Show the button!
	local function Show(dist)
		if (not billboard) and (not billboardVisible) and (not closing) then
			--- Update vars
			billboardVisible = true
			closing = false

			--- Create button and give appropriate button image depending on platform
			billboard = assets.Billboards:FindFirstChild("Interact"):Clone()
			if _L.Variables.Console then
				billboard.Button.Back.Icon.Image = consoleButtonImage
			elseif _L.Variables.Mobile then
				billboard.Button.Back.Icon.Image = mobileButtonImage
			else
				billboard.Button.Back.Icon.Image = desktopButtonImage
			end

			--- Animation
			local cachedSize = billboard.Size
			billboard.Size = UDim2.new()
			_L.Functions.FastTween(billboard, {Size = cachedSize}, {0.2, Enum.EasingStyle.Back, Enum.EasingDirection.Out})

			--- Parent button
			billboard.Adornee = host
			billboard.Parent = _L.Player.Get("PlayerGui")

			--
			Events()
		end
	end

	--- Hide the button!
	local function Hide()
		if billboard and billboardVisible and (not closing) then
			closing = true

			--- Animation
			local animation = _L.Functions.FastTween(billboard, {Size = UDim2.new()}, {0.15, Enum.EasingStyle.Back, Enum.EasingDirection.In})
			animation.Completed:Wait()

			--- Hide the button!
			billboardVisible = false
			billboard:Destroy()
			billboard = nil

			--- Disconnect button events
			for i = 1, #inputEvents do
				inputEvents[i]:Disconnect()
			end
			inputEvents = {}

			--
			closing = false
		end
	end

	--- Destroy the button :(
	local function Remove()
		billboards[billboardId] = nil

		--- Bye bye button :'(
		if skipAnimationOnRemove then
			if billboard then
				billboard:Destroy()
			end
		else
			Hide()
		end

		--- Other cleanup
		if debrisHost and host then
			host:Destroy()
			host = nil
		end
		if currentBillboardId == billboardId then
			currentBillboardId = nil
			currentBillboardDist = nil
		end
	end

	--- Main loop (this could possibly be more efficient by putting functions in the main loop)
	coroutine.wrap(function()
		while billboards[billboardId] and host and host.Parent do
			if currentBillboardId == billboardId then
				if not billboard then
					Show()
				end

			else
				if billboard then
					Hide()
				end
			end

			_L.Services.RunService.RenderStepped:Wait() --- maybe heartbeat is better?
		end
	end)()

	--
	return event.Event, Remove
end


------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------


coroutine.wrap(function()
	while true do
		local player = _L.Player.Get("Player")

		for id, data in pairs(billboards) do
			local host = data.host
			if (not host) or (not host.Parent) then
				billboards[id] = nil --- cleanup
				continue
			end

			if (tick() - data.lastCheck) >= math.min(data.lastDist / 150, 0.5) then
				local pos = host.CFrame.p
				local dist = player:DistanceFromCharacter(pos)
				data.lastDist = dist
				data.lastCheck = tick()

				if dist <= data.maxDist then
					if (not currentBillboardId or dist < (currentBillboardDist - 1)) or (currentBillboardId == id) then
						currentBillboardDist = dist
						currentBillboardId = id
					end
				elseif (currentBillboardId == id) then
					currentBillboardDist = nil
					currentBillboardId = nil
				end
			end
		end

		_L.Services.RunService.Heartbeat:Wait()
	end
end)()


