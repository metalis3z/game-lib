local function TranslateImages()
	for image, translations in pairs(imageTranslations) do
		--- Translate image!
		Language.TranslateImage(image)
	end
end


------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

function Language.TranslateImage(image)
	--- Grab translations for image
	local translations = imageTranslations[image]
	--
	if translations then
		--- Grab translation for selected language
		local translation = translations[language]

		--- Does it exist?
		if translation then
			--- Apply it
			if image.ClassName == "Decal" or image.ClassName == "Texture" then
				image.Texture = translation
			else
				image.Image = translation
			end
		else
			--- No translation found for this image
			_L.Print("Failed to translate image [bold]" .. image.Name .. "[/bold] to [bold]" .. language .. "[/bold]", true)
		end
	else
		--- Failed to index translations for this image
		_L.Print("Failed to index translations for image [bold]" .. image.Name .. "[/bold]", true)
	end
end


function Language.Change(newLanguage)
	--- Convert full term to shortcut term (ie. English -> en-us)
	newLanguage = languageShortcuts[string.lower(newLanguage):gsub("%s+", "")] or newLanguage
	language = (newLanguage or language)

	--- Grab translator
	local success, translator = pcall(function()
		return _L.Services.LocalizationService:GetTranslatorForLocaleAsync(language)
	end)
	if success and translator then
		localTranslator = translator
	else
		_L.Print("Failed to grab translator (" .. language .. ")", true)
	end

	--- Translate
	TranslateImages()
	_L.Signal.Fire("Language Changed", newLanguage)
end


function Language.Get()
	--- Return the current language and translator
	return language, localTranslator
end


function Language.Translate(text, context)
	if localTranslator then
		return localTranslator:Translate(context or game, text) --- default to game for context if not supplied (go-to for non-colliding translations)
	end
end


function Language.AddImage(image, translations)
	--- Check if image doesn't already exist in cache
	if not imageTranslations[image] then
		--- Convert translationName (English --> en-us)
		local newTranslations = {}
		for languageName, key in pairs(translations) do
			local newLanguageName = languageShortcuts[string.lower(languageName):gsub("%s+", "")]
			newTranslations[newLanguageName or languageName] = key
		end

		--- Replace old translations with ones using proper keys
		translations = newTranslations

		--- Add it!
		imageTranslations[image] = translations
		Language.TranslateImage(image)
	end
end


function Language.RemoveImage(image)
	--- Check if image is in the image cache
	if imageTranslations[image] then

		--- Remove it
		imageTranslations[image] = nil
	end
end


