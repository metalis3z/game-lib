	-+-+-+- SPECIFICS -+-+-+-
	_L.Language
	===========

	Adds localization support including images. Has support for language-changing, text translations, and image translations. Image translation is automatic whereas
	any text that isn't already translated using AutoLocalize must be passed through this module (MagicText does this, for example). Language changing doesn't work for
	AutoLocalize text at the moment.
	
	List of languages (and shortcuts) roblox *officially* supports
	English: en-us
	Spanish: es-es
	Portuguese: pr-br
	French: fr-fr
	Korean: ko-kr
	German: de-de
	Russian: ru-ru
	Japanese: ja-jp
	Indonesian: id-id
	Italian: it-it
	Chinese Simplified: zh-cn
	Chinese Traditional: zh-tw
	
	===========
		\\\ Changes local language
		Language.Change(
			language,				<-- |REQ|	Selected language string. Accepts full language and shortcut
		)

		\\\ Translate text based on current language
		Language.Translate(
			text,					<-- |REQ|	Text to translate
		)
		
		\\\ Add images to translate
		Language.AddImage(
			image,					<-- |REQ|	Image, decal instance
			translationTable		<-- |REQ|	Table of translated images and their languages. Accepts full language and shortcut
		)
			EX: _L.Language.AddImage(image, {English = "rbxassetid://3029164791", ["fr-fr"] = "rbxassetid://3029164791"})
			
		\\\ Removes images being translated
		Language.RemoveImage(
			image,					<-- |REQ|	Image, decal instance
		)
		
		\\\ Returns the language and translator in use
		Language.Get()
	===========
