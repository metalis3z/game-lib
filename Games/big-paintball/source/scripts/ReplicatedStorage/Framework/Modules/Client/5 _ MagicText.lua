Text.Apply = function(textLabel, addons, position, propertyChanged, realTextLabel)
	local function findStyle(term)
		for _, style in ipairs(styles) do
			if _L.Functions.SearchArray(style.terms, term) then
				return style
			end
		end
	end

	for addonType, addonValue in pairs(addons) do
		local style = findStyle(addonType)
		if style then
			local success = style.func(textLabel, addonValue, position, addonType, propertyChanged, realTextLabel)
			if not success then
				_L.Print("Failed to apply '" .. addonType .. "' to text (error)", true)
			end
		else
			_L.Print("Failed to apply '" .. addonType .. "' to text (doesn't exist)", true)
		end
	end
end


Text.Draw = function(textLabel, propertyChanged)
	if textLabel.Rotation ~= 0 then
		return Text.Clear(textLabel)
	end

	local text = textLabel.Text
	local frame = mimics[textLabel]
	if not frame then
		frame = Instance.new("Frame")
		mimics[textLabel] = frame
		textLabel.Visible = false
	end

	frame.AnchorPoint = textLabel.AnchorPoint
	frame.BackgroundColor3 = textLabel.BackgroundColor3
	frame.BackgroundTransparency = textLabel.BackgroundTransparency
	frame.BorderColor3 = textLabel.BorderColor3
	frame.BorderMode = textLabel.BorderMode
	frame.BorderSizePixel = textLabel.BorderSizePixel
	frame.LayoutOrder = textLabel.LayoutOrder
	frame.SizeConstraint = textLabel.SizeConstraint
	frame.ZIndex = textLabel.ZIndex
	frame.Position = textLabel.Position
	frame.Size = textLabel.Size
	frame.AutoLocalize = false
	frame.ClipsDescendants = textLabel.ClipsDescendants
	frame.Parent = textLabel.Parent

	if not renderIteration[textLabel] then
		renderIteration[textLabel] = 0
	else
		renderIteration[textLabel] = renderIteration[textLabel] + 1
	end

	local renderNum = renderIteration[textLabel]
	frame.Name = 'MagicText-"' .. textLabel.Name .. '"_MIMIC_#' .. renderNum
	local cachedName = frame.Name

	local textXAlignment = textLabel.TextXAlignment 
	local horizonalAlignment = (((textXAlignment == Enum.TextXAlignment.Center and Enum.HorizontalAlignment.Center) or textXAlignment == Enum.TextXAlignment.Left and Enum.HorizontalAlignment.Left) or textXAlignment == Enum.TextXAlignment.Right and Enum.HorizontalAlignment.Right)
	local textYAlignment = textLabel.TextYAlignment 
	local verticalAlignment = (((textYAlignment == Enum.TextYAlignment.Center and Enum.VerticalAlignment.Center) or textYAlignment == Enum.TextYAlignment.Bottom and Enum.VerticalAlignment.Bottom) or textYAlignment == Enum.TextYAlignment.Top and Enum.VerticalAlignment.Top)

	--- Localize text if possible
	--textLabel.AutoLocalize = false
	text = _L.Language.Translate(text) or text

	local letters = Text.Parse(text)
	local cache = cached[textLabel]
	local physicalLetters = {}
	local usedLetters = {}

	--- Render text letters/parts
	for pos, letterData in ipairs(letters) do
		local char = letterData.char
		local addons = letterData.addons
		local size
		local letter

		if letterData.img then
			--- Image
			letter = (frame and frame:FindFirstChild("img-" .. pos, true)) or Instance.new("ImageLabel")
			letter.Name = "img-" .. pos
			letter.BackgroundTransparency = 1
			letter.BorderSizePixel = 0
			letter.ImageColor3 = textLabel.TextColor3
			letter.ZIndex = frame.ZIndex
			letter.LayoutOrder = pos
			letter.ScaleType = Enum.ScaleType.Fit

			--local ratioConstraint = Instance.new("UIAspectRatioConstraint") --- to keep 1:1
			--ratioConstraint.Parent = letter

			Text.Apply(letter, addons, pos, propertyChanged, textLabel)

			letter.Size = UDim2.new(0, textLabel.TextSize, 0.8, 0)
			size = Vector2.new(textLabel.TextSize, textLabel.TextSize)

		else
			--- Text
			letter = (frame and frame:FindFirstChild("char-" .. pos, true)) or Instance.new("TextLabel")
			letter.Name = "char-" .. pos
			letter.BackgroundTransparency = 1
			letter.BorderSizePixel = 0
			letter.AutoLocalize = false
			letter.ZIndex = frame.ZIndex
			letter.LayoutOrder = pos
			letter.Text = char
			letter.TextColor3 = textLabel.TextColor3
			letter.TextStrokeColor3 = textLabel.TextStrokeColor3
			letter.TextTransparency = textLabel.TextTransparency
			letter.TextStrokeTransparency = textLabel.TextStrokeTransparency
			letter.Font = textLabel.Font
			letter.TextSize = textLabel.TextSize

			Text.Apply(letter, addons, pos, propertyChanged, textLabel)

			size = _L.Services.TextService:GetTextSize(letter.Text, letter.TextSize, letter.Font, frame.AbsoluteSize)
			letter.Size = UDim2.new(0, size.X, 1, 0)
		end

		physicalLetters[pos] = letter
		usedLetters[letter] = true

		if (not frame) then --- Another render is being performed on this textlabel, abort
			letter:Destroy()
			return
		end
	end

	--- Sort and display
	local verticalLayout = frame:FindFirstChild("__verticallayout")
	if not verticalLayout then
		verticalLayout = Instance.new("UIListLayout")
		verticalLayout.FillDirection = Enum.FillDirection.Vertical
		verticalLayout.HorizontalAlignment = Enum.HorizontalAlignment.Center
		verticalLayout.VerticalAlignment = verticalAlignment
		verticalLayout.SortOrder = Enum.SortOrder.LayoutOrder
		verticalLayout.Name = "__verticallayout"
		verticalLayout.Parent = frame
	end

	local horizontalNum = 0
	local horizontalFrame
	local horizontalLayout
	local horizontalTickVal
	local horizontalTextSizeX = 0
	for pos, letter in ipairs(physicalLetters) do
		local letterSize = letter.AbsoluteSize
		horizontalFrame = frame:FindFirstChild("letters_" .. horizontalNum)
		horizontalLayout = horizontalFrame and horizontalFrame:FindFirstChild("__horizontallayout")
		horizontalTickVal = horizontalFrame and horizontalFrame:FindFirstChild("__tick")
		horizontalTextSizeX = horizontalTextSizeX + letterSize.X

		if (not horizontalFrame) or (textLabel.TextWrapped and horizontalTextSizeX > horizontalFrame.AbsoluteSize.X) then
			horizontalNum = horizontalNum + 1
			horizontalTextSizeX = letterSize.X

			horizontalFrame = frame:FindFirstChild("letters_" .. horizontalNum)
			horizontalLayout = horizontalFrame and horizontalFrame:FindFirstChild("__horizontallayout")
			horizontalTickVal = horizontalFrame and horizontalFrame:FindFirstChild("__tick")

			if (not horizontalFrame) then
				horizontalFrame = Instance.new("Frame")
				horizontalFrame.BackgroundTransparency = 1
				horizontalFrame.BorderSizePixel = 0
				horizontalFrame.Size = UDim2.new(1, 0, 0, 0)
				horizontalFrame.LayoutOrder = horizontalNum
				horizontalFrame.Name = "letters_" .. horizontalNum
				horizontalFrame.Size = UDim2.new(1, 0, 0, textLabel.TextSize)

				horizontalLayout = Instance.new("UIListLayout")
				horizontalLayout.FillDirection = Enum.FillDirection.Horizontal
				horizontalLayout.VerticalAlignment = Enum.VerticalAlignment.Center
				horizontalLayout.SortOrder = Enum.SortOrder.LayoutOrder
				horizontalLayout.Name = "__horizontallayout"
				horizontalLayout.Parent = horizontalFrame

				horizontalTickVal = Instance.new("IntValue")
				horizontalTickVal.Name = "__tick"
				horizontalTickVal.Parent = horizontalFrame
			end
		end

		horizontalFrame.ZIndex = frame.ZIndex
		horizontalLayout.HorizontalAlignment = horizonalAlignment
		horizontalTickVal.Value = renderNum
		letter.Parent = horizontalFrame
		horizontalFrame.Parent = frame
	end

	for _, horizontalFrame in ipairs(frame:GetChildren()) do
		if horizontalFrame.ClassName == "Frame" then
			local t = horizontalFrame:FindFirstChild("__tick")
			if t and t.Value ~= renderNum then
				horizontalFrame:Destroy()
			elseif t then
				for _, letter in ipairs(horizontalFrame:GetChildren()) do
					if (letter.ClassName == "TextLabel" or letter.ClassName == "ImageLabel") and (not usedLetters[letter]) then
						letter:Destroy()
					end
				end
			end
		end
	end

	--- Cache
	cached[textLabel] = letters
end


Text.Parse = function(text)
	if textParseCache[text] then
		return textParseCache[text].solve
	end
	--local textCleared = string.gsub(text, "%<.->", ""):gsub("%<.-/>", "")

	local letters = {}
	local addons = {}
	local letterNum = 1
	local ignoreNum = 0

	for first, last in utf8.graphemes(text) do
		ignoreNum = math.max(ignoreNum - 1, 0)

		if ignoreNum <= 0 then
			local letter = string.sub(text, first, last)
			local decodable = false

			if letter == "<" then
				local markupType
				local markupValue
				local openingStart, openingEnd

				local s = string.sub(text, first)
				local uncleanMarkupType = string.match(s, ".-=")
				local uncleanMarkupValue = string.match(s, "=.+>-")

				if uncleanMarkupType and uncleanMarkupValue then
					markupType = uncleanMarkupType:match("[^<=]+")
					markupValue = uncleanMarkupValue:match("[^>=]+")
					openingStart, openingEnd = string.find(s, "<" .. markupType .. "=" .. markupValue .. ">", 1, true)
					decodable = (openingStart ~= nil)

					if decodable then
						ignoreNum = ignoreNum + string.len("<" .. markupType .. "=" .. markupValue .. ">")
						if markupType == "i" or markupType == "img" or markupType == "image" then
							--- image support (create a custom character)
							local clonedAddons = _L.Functions.CloneTable(addons)
							clonedAddons[markupType] = markupValue
							if letters[letterNum] then
								letterNum = letterNum + 1
							end
							letters[letterNum] = {
								char = "",
								img = true,
								pos = letterNum,
								addons = clonedAddons,
							}
						else
							--- normal addon
							addons[markupType] = (markupValue ~= "/" and markupValue or nil)
						end
					else
						_L.Print("Failed to parse markdown for " .. (markupType or "'nil'"), true)
					end
				end
			end

			if not decodable then
				if wordSupport then
					local function AddonsForceLetters()
						for addonType, addonValue in pairs(addons) do
							for _, styleData in ipairs(styles) do
								if _L.Functions.SearchArray(styleData.terms, addonType) then
									if styleData.forceLetters then
										return true
									end
								end
							end
						end
					end

					--- Words supported
					if (not letters[letterNum]) or (not _L.Functions.CompareTable(letters[letterNum].addons, addons, true) or AddonsForceLetters()) then
						if letters[letterNum] then
							letterNum = letterNum + 1
						end
						letters[letterNum] = {
							char = letter, 
							pos = letterNum,
							addons = _L.Functions.CloneTable(addons),
						}
					else
						letters[letterNum].char = letters[letterNum].char .. letter
						if string.match(letter, "%s") then
							letterNum = letterNum + 1
						end
					end

				else
					--- Word support turned off (individual letters only)
					letterNum = letterNum + 1
					letters[letterNum] = {
						char = letter, 
						pos = letterNum,
						addons = _L.Functions.CloneTable(addons),
					}
				end
			end
		end
	end

	if not textParseCache[text] then --- Update cache
		textParseCache[text] = {solve = letters, lastTick = tick()}
	else
		textParseCache[text].lastTick = tick()
	end

	return letters

	--[[local text = game.StarterGui.ScreenGui.Frame.TextLabel.Text
