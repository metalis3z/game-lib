Text.Clear = function(textLabel)
	local frame = mimics[textLabel]
	if frame then
		frame:Destroy()
		mimics[textLabel] = nil
		cached[textLabel] = nil
		renderIteration[textLabel] = nil
		textLabel.Visible = true
	end
end


Text.Check = function(textLabel, property)
	local text = textLabel.Text

	if text ~= nil and text ~= "" and (not textLabel.RichText) then
		if string.match(text, catchPattern) then
			--			local vis = textLabel.Visible
			--			if (not Text.IsRendering(textLabel)) and (not vis) then
			--				return false
			--			end
			return true
		end
	end

	return false
end


Text.Track = function(textLabel)
	local lastCheck
	local ignoreUntilVisible = not textLabel.Visible --- Do not render until visiblity is true (for first time only cus logic issues)

	if tracking[textLabel] then
		return
	else
		tracking[textLabel] = true
	end

	local function Update(property)
		if property == "text" or property == "visible" or property == "init" then
			if (not textLabel.Visible) and ignoreUntilVisible then
				return
			end

			lastCheck = Text.Check(textLabel, property)

			if lastCheck then
				if not _ENABLED then
					textLabel.Text = RemoveMarkup(textLabel.Text)
					return
				end
				ignoreUntilVisible = false
			end
		end

		if lastCheck then
			Text.Draw(textLabel, property)
		else
			Text.Clear(textLabel)
		end
	end
	Update("init")

	--- Property changed
	textLabel.Changed:Connect(function(property)
		property = string.lower(property)
		if (property == "text" and (not lastCheck)) or (lastCheck and _L.Functions.SearchArray(importantProperties, property)) then
			Update(property)
		end
	end)

	--- When deleted
	textLabel.AncestryChanged:Connect(function()
		if not textLabel:IsDescendantOf(game) then
			Text.Clear(textLabel)
		end
	end)
end


Text.Scan = function()
	local function Scan(p)
		for i, gui in ipairs(p:GetDescendants()) do
			if gui.ClassName == "TextLabel" then
				coroutine.wrap(function()
					Text.Track(gui)
				end)()
			elseif i%80 == 0 then
				_L.Services.RunService.RenderStepped:Wait()
			end
		end
	end

	--- Scan playergui (ignoring coreguis and custom ignore screenguis)
	local playerGui = _L.Player.Get("PlayerGui")
	for _, gui in ipairs(playerGui:GetChildren()) do
		if game.StarterGui:FindFirstChild(gui.Name) and (not _L.Functions.SearchArray(playerGuiIgnore, gui.Name)) then
			Scan(gui)
		end
	end

	--- Scan workspace
	Scan(game.Workspace)
end


