	_L.MagicText
	===========
	
	An elaborate, robust, hands-free, and efficient approach to roblox's lack of native mark-up text support. Any textlabel in the game supports markup text without
	altering the textlabel itself. This is done by making a *cloned* version of the text which is parented under the same instance. This is done in a way that is
	completely un-noticable. You will not have to alter any of your code. There is nothing else like it.
	
	Pros:
	- No coding or plugging-in required. All done *automatically* in run-time, like magic
	- Supports mashing+mixing text types, images, and animated effects
	- Custom effects and markup types can be added in minutes - very customizable!
	- Very readable syntax similar to html
	- SurfaceGui+BillboardGui support
	- Supports wrapped markup (ie. <t=bold><c=red> hello! <t=/><c=/>
	- Very efficient (only changes what needs to be changed every render)
	- Instant render times
	- Proper error handling and perfect string matching
	- Does not affect workflow whatsoever
	- Supports (~almost) every property of a TextLabel
	- Cross compatibility
	
	Limitations:
	- Does not support TextScaled. This is impossible to calculate at the moment without insane performance hits. You must design
	your interface around offset scaling or create a hardcoded scaling system for your specific interface
	- MAY NOT work if textlabel is directly affected by UIGridLayout, UIListLayout, UIPageLayout, or UIInlineLayout. In my testing it DOES,
	but it isn't supported. This is at the mercy of roblox's GUI engineers at the moment
	- Proper word alignment only works for markup effects with 'forceLetters' set to false
	- Doesn't support rotation
	- Doesn't support changing visibility
	
	Examples:
	
	"This text has <c=red>red<c=/> in it!"
	
	"This text has <t=bold>bold text<t=/> in it!"
	
	"<rainbow=0.4>This text is rainbow!<rainbow=/>"
	
	"This text is <t=bold>bold<t=/> and <c=(255, 0, 0)>red<c=/>!"
	
	"<c=random>This text is a random color!<c=/>"
	
	"This item costs <img=robux><c=green><t=bold>100<c=/><t=/> robux!"
	
	"Here are some images: <img=4736911792> <img=rbxassetid://4736911792> <img=robux>"
	
	"You unlocked a <boom=1><c=yellow>LEGENDARY<c=/> <t=italic>Laser Gun!<t=/><boom=/>"
	
	"<c=(100,40,30)>You don't need an escape bracket if you don't want one!"
	
	"<rainbow=0.145>You can <t=semibold>split<t=/> effects if you <c=red>want!<rainbow=/> and it works!<c=/>"
	
