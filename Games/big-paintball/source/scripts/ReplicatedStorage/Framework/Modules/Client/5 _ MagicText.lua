local styles = {
	-----------------------===== COLOR =====-----------------------

	{	
		terms = {"c", "color"},
		forceLetters = false, --- force seperation of words into letters (used for special FX)
		--
		func = function(textLabel, value, position, termUsed, propertyChanged, realTextLabel)
			--- Random
			if string.lower(value) == "random" then
				local rngColor = Color3.new(rng:NextNumber(), rng:NextNumber(), rng:NextNumber())
				if textLabel.ClassName == "ImageLabel" then
					textLabel.ImageColor3 = rngColor
				else
					textLabel.TextColor3 = rngColor
				end
				return true
			end

			--- Color3 (x, x, x)
			local color3Match = string.match(value, "%b()")
			if color3Match then
				local rgb = {}
				string.gsub(color3Match, "%d+", function(s)
					table.insert(rgb, tonumber(s))
					return
				end)
				if #rgb == 3 then
					local color = Color3.fromRGB(unpack(rgb))
					if textLabel.ClassName == "ImageLabel" then
						textLabel.ImageColor3 = color
					else
						textLabel.TextColor3 = color
					end
					return true
				else
					_L.Print('Failed to apply color to text "' .. textLabel.Text .. '" (missing color3 arg #' .. #rgb+1 .. ')', true)
				end
			end

			--- Preset (words)
			local presetColors = _L.Settings.MagicTextColorCodes
			local presetColor = presetColors[string.lower(value)]
			if presetColor then
				if textLabel.ClassName == "ImageLabel" then
					textLabel.ImageColor3 = presetColor
				else
					textLabel.TextColor3 = presetColor
				end
				return true
			else
				_L.Print('Failed to apply color to text "' .. textLabel.Text .. '" ("' .. value .. '" is not set)', true)
			end
		end,
	},

	-----------------------===== BOLD & ITALICS =====-----------------------

	{	
		terms = {"t", "type"},
		forceLetters = false, --- force seperation of words into letters (used for special FX)
		--
		func = function(textLabel, value, position, termUsed, propertyChanged, realTextLabel)
			if textLabel.ClassName ~= "TextLabel" then
				return
			end

			--- Grab font type alternatives
			local alternatives
			for _, set in ipairs(fontAlternatives) do
				for _, alternative in pairs(set) do
					if alternative == textLabel.Font then
						alternatives = set
						break
					end
				end
			end

			--- Apply (if exists)
			if alternatives and alternatives[string.lower(value)] then
				textLabel.Font = alternatives[string.lower(value)]
				return true
			else
				_L.Print('Failed to apply font type to text "' .. textLabel.Text .. '" (' .. value .. ' does not exist)', true)
			end
		end,
	},

	-----------------------===== IMAGE =====-----------------------

	{	
		terms = {"i", "img", "image"},
		forceLetters = true, --- force seperation of words into letters (used for special FX)
		--
		func = function(textLabel, value, position, termUsed, propertyChanged, realTextLabel)
			if textLabel.ClassName ~= "ImageLabel" then
				return
			end

			--- Link
			local isStringID = string.find(value, "rbxassetid://", 1, true) or string.find(value, "roblox.com/asset/?id=", 1, true)
			if isStringID then
				textLabel.Image = value
				return true
			end

			--- ID
			local isID = string.match(value, "%d+")
			if isID then
				textLabel.Image = "rbxassetid://" .. value
				return true
			end

			--- Asset
			local imgAsset = imageAssets:FindFirstChild(value)
			if imgAsset then
				textLabel.Image = imgAsset.Image
				return true
			end

			_L.Print('Failed to create image "' .. value .. '" (does not exist in ReplicatedStorage/Assets/MagicTextImgs)', true)
		end,
	},

	-----------------------===== SPECIAL =====-----------------------

	---- Rainbow (Rainbow color wave)
	{	
		terms = {"rainbow"},
		forceLetters = true, --- force seperation of words into letters (used for special FX)
		--
		func = function(textLabel, value, position, termUsed, propertyChanged, realTextLabel)
			local speed = tonumber(value) or 1
			coroutine.wrap(function()
				local cachedRenderIteration = renderIteration[realTextLabel]
				while textLabel and cachedRenderIteration == renderIteration[realTextLabel] do
					local i = ((tick() / 10 * speed) + (position / 10))%1
					local color = Color3.fromHSV(i, 0.9, 0.9)
					if textLabel.ClassName == "ImageLabel" then
						textLabel.ImageColor3 = color
					else
						textLabel.TextColor3 = color
					end
					_L.Services.RunService.Heartbeat:Wait() --- could be renderstepped but 60hz is more performant
				end
			end)()
			return true
		end,
	},

	---- Word pop (each letter pops out and shrinks back to default size)
	{	
		terms = {"boom", "pop"},
		forceLetters = true, --- force seperation of words into letters (used for special FX)
		--
		func = function(textLabel, value, position, termUsed, propertyChanged, realTextLabel)
			if textLabel.ClassName ~= "TextLabel" then
				return
			end
			local speed = 0.45
			local size = tonumber(value) or 5
			coroutine.wrap(function()
				local cachedRenderIteration = renderIteration[realTextLabel]
				local endTick = tick()+speed
				local cachedTextSize = textLabel.TextSize
				while textLabel and cachedRenderIteration == renderIteration[realTextLabel] and tick() <= endTick do
					local a = 1 - math.clamp((endTick - tick()) / speed, 0, 1)
					textLabel.TextSize = cachedTextSize + math.sin(a*math.pi)*size
					_L.Services.RunService.Heartbeat:Wait() --- could be renderstepped but 60hz is more performant
				end
				if textLabel then
					textLabel.TextSize = cachedTextSize
				end
			end)()
			return true
		end,
	},
}


