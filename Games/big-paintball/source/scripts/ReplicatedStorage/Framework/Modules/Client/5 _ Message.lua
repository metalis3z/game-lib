function Message.New(message, ...)
	local args = {...}

	--- Another message is already open
	if _L.Variables.MessageOpen == true then
		--- Wait for old message to go away
		repeat _L.Services.RunService.RenderStepped:wait() until _L.Variables.MessageOpen == false
	end

	--- Setup vars
	local isStatement = (args[1] == nil and args[2] == nil)
	local isQuestion = (type(args[1]) == "boolean" and args[2] == nil)
	local isOptions = (args[1] and args[2])

	--- Setup message buttons according to message type
	GUI.Yes.Visible = false
	GUI.No.Visible = false
	GUI.Ok.Visible = false
	GUI.Option1.Visible = false
	GUI.Option2.Visible = false
	GUI.Cancel.Visible = false
	GUI.Desc.Text = message

	--- Desc text shadow
	for _, shadow in ipairs(GUI.Desc:GetChildren()) do
		if shadow.ClassName == "TextLabel" then
			shadow.Text = GUI.Desc.Text
		end
	end

	--
	if not isStatement then
		if isQuestion then
			--- Yes/No query
			local decision = args[1]
			GUI.Yes.Visible = true
			GUI.No.Visible = true
		elseif isOptions then
			--- Options
			local option1 = args[1]
			local option2 = args[2]
			GUI.Option1.TextLabel.Text = option1
			GUI.Option2.TextLabel.Text = option2
			GUI.Option1.Visible = true
			GUI.Option2.Visible = true
			GUI.Cancel.Visible = true
		end
	else
		--- Message statement
		GUI.Ok.Visible = true
	end

	--- Click function for buttons
	local result
	--
	local function SetupClickEvent(button, func)
		clickEvents[#clickEvents + 1] = button.MouseButton1Click:Connect(function()
			if clickDeb == false then
				clickDeb = true
				-- Click sound
				_L.Audio.Play(5074101610, game.Players.LocalPlayer.PlayerGui)
				func()
				clickDeb = false
			end
		end)
	end

	--- Give buttons actions by attaching to SetupClickEvent
	if GUI.No.Visible then
		SetupClickEvent(GUI.No, function()  Close()  result = false  end)
	end
	if GUI.Yes.Visible then
		SetupClickEvent(GUI.Yes, function()  Close()  result = true  end)
	end
	if GUI.Ok.Visible then
		SetupClickEvent(GUI.Ok, function()  Close()  result = true  end)
	end
	if GUI.Option1.Visible then
		SetupClickEvent(GUI.Option1, function()  Close()  result = 1  end)
	end
	if GUI.Option2.Visible then
		SetupClickEvent(GUI.Option2, function()  Close()  result = 2  end)
	end
	if GUI.Cancel.Visible then
		SetupClickEvent(GUI.Cancel, function()  Close()  result = false  end)
	end

	--- Console compatibility
	if _L.Variables.Console then
		if GUI.Ok.Visible then
			_L.Services.GuiService.SelectedObject = GUI.Ok
		elseif GUI.Yes.Visible then
			_L.Services.GuiService.SelectedObject = GUI.Yes
		elseif GUI.Option1.Visible then
			_L.Services.GuiService.SelectedObject = GUI.Option1
		end

		local exitEventDeb = false
		clickEvents[#clickEvents + 1] = _L.Services.UserInputService.InputEnded:Connect(function(input, processed)
			if not exitEventDeb then
				exitEventDeb = true
				if input.KeyCode == Enum.KeyCode.ButtonB then
					_L.Audio.Play(5074101610, game.Players.LocalPlayer.PlayerGui)
					Close()
				end
				exitEventDeb = false
			end
		end)
	end

	--- Audio
	if isStatement then
		_L.Audio.Play(5205170754, script, 1, 0.7) -- appear
	elseif isQuestion or isOptions then
		_L.Audio.Play(5205170754, script, 1, 0.7) -- warning
	end

	--- Make message visible
	Open()

	--- Wait until message is closed
	repeat _L.Services.RunService.RenderStepped:wait() until result ~= nil

	--
	return result
end


------------------------------------------------------------------------------

function Message.IsOpen()
	return GUI.Gui.Enabled
end

function Close()
	--- Clear button events
	for _, v in ipairs(clickEvents) do
		v:Disconnect()
	end
	clickEvents = {}

	--- Close message GUI
	GUI.Gui.Enabled = false
	_L.Variables.MessageOpen = false
end


function Open()
	--- Open message GUI
	GUI.Gui.Enabled = true
	_L.Variables.MessageOpen = true
end


