	_L.Message
	===========
	Creates a pop-up message or dialog on the user's screen. You have 3 options to use this:
	- Message statement
		_L.Message.Send(message)
	- Yes/no dialog
		_L.Message.Send(message, true)
	- 2 question dialog
		_L.Message.Send(message, "One Pet", "Two Pets")
	Results for latter will be returned as either (true / false)  /  (1 / 2) depending on dialog
	
	===========
		\\\ Posts a message on the player with the given arguments
		Message.New(
			message,						<-- |REQ|	Message of the dialog
