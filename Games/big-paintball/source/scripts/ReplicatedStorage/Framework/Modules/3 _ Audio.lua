--- Pile onto garbage collection
function AddToGarbageCollection(sound, parentWasGenerated)
	--- Add to garbage collection
	table.insert(garbage, {sound, parentWasGenerated or false})
end


--- Scan garbage collection for GARBAGE
function ScanGarbageCollection()
	for i = #garbage, 1, -1 do
		if i%25 == 0 then
			_L.Services.RunService.Heartbeat:Wait()
		end

		--- Variables
		local garbageArray = garbage[i]
		local garbageItem = garbageArray[1]
		local garbageParentWasGenerated = garbageArray[2]
		local due = false

		--- Sanity check
		if not due then
			if (not garbageItem) or (not garbageItem.Parent) then
				due = true
			end
		end

		--- Stopped check #1
		if not due then
			local playing = garbageItem.Playing
			if not playing then
				due = true
			end
		end

		--- Empty sound check
		if not due then
			local soundId = garbageItem.SoundId
			if soundId == "" then
				due = true
			end
		end

		--- Remove if due
		if due then
			if garbageParentWasGenerated then
				if garbageItem.Parent then
					garbageItem.Parent:Destroy()
				end
			elseif garbageItem then
				garbageItem:Destroy()
			end
			table.remove(garbage, i)
		end
	end

	--- Debug
	if isClient then
		_L.Debug.Track("Garbage #", "Audio", #garbage)
	end
end


--- Main garbage collection
coroutine.wrap(function()
	if isClient then
		while true do
			--- Wait
			wait(1)

			--- Scan garbage
			ScanGarbageCollection()

			--- Music debug
			local musicPlaying = false
			for _, music in ipairs(musicFolder:GetChildren()) do
				musicPlaying = true
				break
			end
			_L.Debug.Track("Music Playing", "Audio", musicPlaying)
		end
	end
end)()


--- Disabled sounds
coroutine.wrap(function()
	local last = _L.Settings.SoundsEnabled
	while wait() do
		if last ~= _L.Settings.SoundsEnabled then
			last = _L.Settings.SoundsEnabled

			--- Scan all active sounds
			for i, v in pairs(garbage) do
				local sound = v[1]
				if sound and sound.Parent ~= musicFolder then
					if not last then
						--- Mute sound and cache volume
						local cacheVal = _L.Functions.QuickValue(sound.Volume)
						cacheVal.Name = "%CACHEDVOLUME"
						cacheVal.Parent = sound
						sound.Volume = 0

					elseif sound:FindFirstChild("%CACHEDVOLUME") then
						--- Change volume back
						local cacheVal = sound:FindFirstChild("%CACHEDVOLUME")
						sound.Volume = cacheVal.Value
						cacheVal:Destroy()
					end
				end
			end
		end
	end
end)()


--- Recieve sounds from server
if isClient then
	_L.Network.Fired("PlaySound"):Connect(function(...)
		Audio.Play(...)
	end)
end


