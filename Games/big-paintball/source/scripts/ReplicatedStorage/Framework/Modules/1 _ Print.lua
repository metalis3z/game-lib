--- If false, will default to normal printing
local enabled = true

--- Include tags
local tagsEnabled = true

--- Include emojis
local emojisEnabled = true

--- Enable warn color (includes timestamp)
local warnColorEnabled = false

--- Include the FULL path for TG_1SdMQWoddNBGG8
local includeScriptPath = false

--- Include line # where print was executed
local includeLineNumber = true

--- Include 'Server' or 'Client'
local includeParentSub = false

--------|     Library     |--------
local _L; coroutine.wrap(function()  _L = require(game.ReplicatedStorage:WaitForChild("Framework"):WaitForChild("Library"))  end)()

--------|    Reference    |--------
local framework = game.ReplicatedStorage:WaitForChild("Framework")

