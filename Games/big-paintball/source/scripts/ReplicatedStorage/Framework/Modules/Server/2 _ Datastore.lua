		end
	until success or attempts >= maxUpdateAttempts

	--- Debug prints
	if Debug then
		if attempts >= maxUpdateAttempts then
			_L.Print("Failed to update key --- [bold]" .. key .. "[/bold]", true)
		end
	end

	--
	return success
end


