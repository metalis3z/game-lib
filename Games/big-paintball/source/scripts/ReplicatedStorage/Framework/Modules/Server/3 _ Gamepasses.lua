--- Player joined
game.Players.PlayerAdded:Connect(function(player)
	--- Check for new gamepasses
	CheckPlayer(player)	
end)


--- Player left
game.Players.PlayerRemoving:Connect(function(player)
	--- Remove from cache
	RemovePlayer(player)	
