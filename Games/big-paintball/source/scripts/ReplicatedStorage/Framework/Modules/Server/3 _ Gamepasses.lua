function Gamepasses.Owns(player, gamepassId)
	--- Variables
	local playerId = player.UserId
	local playerStats = _L.Storage.Stats["u" .. playerId]

	--- Does player's stats exist?
	if playerStats ~= nil then
		--- Iterate through gamepasses owned
		for _, otherGamepassId in pairs(playerStats.Gamepasses) do
			if tostring(otherGamepassId) == tostring(gamepassId) then
				--- Player owns this gamepass!
				return true
			end
		end
	end

	--
	return false
end


function Gamepasses.OwnsAmount(player)
	--- Variables
	local gamepassesOwned = 0

	--- Iterate through all existing gamepasses
	for _, gamepassInfo in pairs(_L.Directory.Gamepasses) do
		local gamepassId = gamepassInfo.ID
		local gamepassOwned = Gamepasses.Owns(player, gamepassId)

		--- Player owns this gamepass! +1
		if gamepassOwned then
			gamepassesOwned = gamepassesOwned + 1
		end
	end

	--
	return gamepassesOwned
end


