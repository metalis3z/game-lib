Products.GetDir = function(id)
	--- Search for the product dir with matching ID
	for _, productDir in pairs(_L.Directory.Products) do
		if tostring(productDir.ID) == tostring(id) then
			return productDir
		end
	end

	--- Error
	_L.Print('Product ID "' .. id .. '" does not exist in the Directory', true)
end


