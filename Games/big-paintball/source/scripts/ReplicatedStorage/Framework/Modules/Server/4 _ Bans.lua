--- Returns if player is banned
Bans.IsBanned = function(playerId)
	--- accepts player and playerid
	if type(playerId) == "userdata" and playerId.ClassName == "Player" then
		playerId = playerId.UserId
	end

	local profile = Bans.GetProfile(playerId)

	if profile then
		return profile.IsBanned
	end

	--
	return false
end


--- Returns if player is warned
Bans.IsWarned = function(playerId)
	--- accepts player and playerid
	if type(playerId) == "userdata" and playerId.ClassName == "Player" then
		playerId = playerId.UserId
	end

	local profile = Bans.GetProfile(playerId)

	if profile then
		local timeLeft = warnTime - (os.time() - profile.WarnTick)
		local timeLeftText = _L.Functions.TimeString(timeLeft)
		if profile.IsWarned and timeLeft > 0 then
			return true, timeLeftText
		end
	end

	--
	return false
end


--- Returns if player has ban profile
Bans.HasProfile = function(playerId)
	return (Bans.GetProfile(playerId) ~= nil)
end


--- Get player's ban profile
Bans.GetProfile = function(playerId, avoidCache)
	--- accepts player and playerid
	if type(playerId) == "userdata" and playerId.ClassName == "Player" then
		playerId = playerId.UserId
	end

	local avoidCache = (avoidCache == nil) or avoidCache == false or avoidCache
	local player = game.Players:GetPlayerByUserId(playerId)

	--- Check cache
	if profileCache[playerId] and profileCacheTimers[playerId] and not avoidCache then
		--- Check cache buffer
		if tick() - profileCacheTimers[playerId] <= profileCacheBuffer then
			--- Returned cached profile
			return profileCache[playerId]
		end
	end

	--- Get profile from datastore (instead of cache)
	local profile = _L.Datastore.Get(profileDS, playerId)

	if profile and (not profileCache[playerId]) then
		profileCache[playerId] = profile
		profileCacheTimers[playerId] = tick()
	end

	--
	return profile
end


--- Update player's ban profile
Bans.UpdateProfile = function(playerId, custom)
	--- accepts player and playerid
	if type(playerId) == "userdata" and playerId.ClassName == "Player" then
		playerId = playerId.UserId
	end

	local player = game.Players:GetPlayerByUserId(playerId)
	local accountAge
	local membership
	local gamepasses
	local lastUpdate

	local save
	if player then
		save = _L.Saving.Get(player)
		if save then
			accountAge = player.AccountAge
			membership = tostring(player.MembershipType)
			gamepasses = _L.Gamepasses.OwnsAmount(player)
			lastUpdate = os.time()
		end
	end

	--- Update datastore with new profile
	_L.Datastore.Update(profileDS, playerId, function(old)
		--- 'Analytical' stats
		if save then
			old.AccountAge = accountAge
			old.Membership = membership
			old.Gamepasses = gamepasses
			old.LastUpdate = lastUpdate
			old.Paid = save.PaidPlayer
			old.RobuxSpent = save.RobuxSpent
		end

		--- Warnings
		if old.IsWarned and (os.time() - old.WarnTick) >= warnTime then
			old.IsWarned = false
			old.WarnTick = 0
		end

		--- Update any variables passed down from 'custom' argument
		if custom then
			for pName, pVar in pairs(custom) do
				old[pName] = pVar
			end
		end

		--- Update cache
		profileCache[playerId] = old
		profileCacheTimers[playerId] = tick()

		--
		return old
	end)
end


--- Create a ban profile for player
Bans.CreateProfile = function(playerId)
	--- accepts player and playerid
	if type(playerId) == "userdata" and playerId.ClassName == "Player" then
		playerId = playerId.UserId
	end

	local player = game.Players:GetPlayerByUserId(playerId)
	local save = _L.Saving.Get(player)

	if player and save then
		--- Grab stats for profile :D
		local profile = {
			History = {},
			IsBanned = false,
			IsWarned = false,
			WarnTick = 0,
			Bans = 0,
			Warns = 0,
			Unbans = 0,
			AccountAge = player.AccountAge,
			Membership = tostring(player.MembershipType),
			Gamepasses = _L.Gamepasses.OwnsAmount(player),
			LastUpdate = os.time(),
			Paid = save.PaidPlayer,
			RobuxSpent = save.RobuxSpent,
		}

		--- Update datastore
		_L.Datastore.Set(profileDS, player.UserId, profile)

		--- Update cache
		profileCache[playerId] = profile
		profileCacheTimers[playerId] = tick()

		--
		return profile
	end
end


--- Get recent list for player
Bans.GetRecentList = function(pageNum)
	--- Grab cache...?
	if recentCache[pageNum] and (tick() - recentCacheTimers[pageNum]) >= recentCacheBuffer then
		return recentCache[pageNum]
	end

	local page = {}
	local pages = recentDS:GetSortedAsync(false, 100)
	local pageCurrent = 1

	--- Iterate through list
	while true do
		local data = pages:GetCurrentPage() 
		local thisPage = {}

		for i, pair in ipairs(data) do
			--- Decompress key via JSON
			local json = _L.Services.HttpService:JSONDecode(pair.key)

			--- Data variables
			local infractionDate = pair.value
			local infractionTimePassed	 = (os.time() - infractionDate)
			local infractionType = json.t
			local moderatorId = json.m
			local victimId = json.v

			--- Convert data to readable state
			table.insert(thisPage, i, {d = infractionDate, tp = infractionTimePassed, t = infractionType, m = moderatorId, v = victimId})
		end

		--- Update cache
		recentCache[pageCurrent] = thisPage
		recentCacheTimers[pageCurrent] = tick()

		--- Update page number
		if pageCurrent == pageNum then
			page = thisPage
		end

		if (pages.IsFinished or pageCurrent == pageNum) then
			break
		else
			--- ADVANCE TO THE NEXT PAGE!
			pages:AdvanceToNextPageAsync()
			pageCurrent = pageCurrent + 1
		end
	end

	--
	return page
end


