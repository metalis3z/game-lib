function TrackPlayer(player)
	--- Main loop - check if the player gets banned mid session and update their player profile
	coroutine.wrap(function()
		--- Wait for player to get past intro
		while (not _L.Saving.IsLoaded(player)) and player do  wait(1)  end

		if (not player) then
			return
		end

		while (player and game.Players:FindFirstChild(player.Name)) do
			local profile = (Bans.GetProfile(player.UserId) or Bans.CreateProfile(player.UserId))

			if not _L.Admins.IsAdmin(player) then --- admins are immune to bans and warnings
				local isBanned = Bans.IsBanned(player.UserId)
				local isWarned = Bans.IsWarned(player.UserId)

				--- Player was naughty.
				if isBanned or isWarned then
					local kick = false
					if isWarned then
						local timeLeft = warnTime - (os.time() - profile.WarnTick)
						if timeLeft > 0 then
							kick = true
						end
					else
						kick = true
					end

					--- Naughty
					if kick then
						player:Kick("Please rejoin.")
					end
				end
			end

			--- Wait random time so datastores don't crash on mass server restart
			wait(checkCooldown * rng:NextNumber(0.5, 1))

			if player and game.Players:FindFirstChild(player.Name) and (not isStudio) then
				Bans.UpdateProfile(player.UserId)
			end
		end
	end)()
end


--- Loop through all players (that might have joined before this code was run)
for _, player in ipairs(game.Players:GetPlayers()) do
	TrackPlayer(player)
end


--- Add tracking device to all players who join server
game.Players.PlayerAdded:Connect(function(player)
	TrackPlayer(player)
end)  


