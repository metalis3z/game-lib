--- Ban player
Bans.Ban = function(playerId, moderatorId, moderatorReason)
	--- accepts player and playerid
	if type(playerId) == "userdata" and playerId.ClassName == "Player" then
		playerId = playerId.UserId
	end 

	moderatorId = moderatorId or 1
	moderatorReason = moderatorReason or "Automated"

	if Bans.IsBanned(playerId) == false then
		local profile = Bans.GetProfile(playerId, true)

		if profile then
			--- Add to history
			table.insert(profile.History, 1, {type = "Ban", moderator = moderatorId, reason = moderatorReason, date = os.time()})

			--- Update profile
			Bans.UpdateProfile(playerId, 
				{
					History = profile.History,
					Bans = profile.Bans + 1,
					IsBanned = true,
				})

			--- Wait (prevents errors, just in case!)
			wait(2)

			--- Set to datastore
			local success = _L.Datastore.Set(recentDS, _L.Services.HttpService:JSONEncode({t = "Ban", m = moderatorId, v = playerId}), os.time())

			--- Kick the player if they are in the server
			local player = game.Players:GetPlayerByUserId(playerId)
			if success and player then
				player:Kick("Please rejoin.")
				_L.Network.FireAll("Chat Msg", player.Name .. " was banned permanently.", Color3.fromRGB(255, 60, 60))
			end

			--- Debug
			if success then
				_L.Print("Successfully banned [bold]" .. playerId .. "[/bold]", true)
				return true

			else
				_L.Print("May have failed to ban [bold]" .. playerId .. "[/bold]", true)
			end

		else
			_L.Print("Player doesn't have profile ([bold]" .. playerId .. "[/bold])", true)
		end

	else
		_L.Print("Player is already banned ([bold]" .. playerId .. "[/bold])", true)
	end

	--
	return false
end


