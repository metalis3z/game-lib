-- The shop. Entries have the shape ShopLibrary.Entries uses:
--
--   { EntryName, EntryType = "Loose" | "Lootbox", Rewards = { reward }, Prices = { [dataField] = n },
--     MainCurrency, PurchaseStartTime, PurchaseDuration, PurchaseAppearTime }
--
-- where a price's key is the data field it is paid from (WeaponKeys, Glory, SkinTickets).
--
--   Data.RequestDailyShop()                  -> { Day, TimeRemaining, Data = { entry } }
--   Data.UpdateDailyShop(same)                  pushed after a refresh or at 00:00 UTC
--   Data.BuyShopEntry(entryName, currency, amount, intendedDay)
--   Data.RefreshDailyShop(intendedDay)          LootLibrary:GetCostToRefreshDailyShop(refreshesToday) keys
--
-- The daily rotation was generated by the original server and is not in the dump. The only
-- daily stock the dump defines is ShopLibrary.DailyShopCosmeticTypes (emotes, priced by
-- rarity), so the rotation is DAILY_EMOTES of those, seeded by the shop day. The client works
-- out that day as Day + DailyShopSeedShift, and a paid refresh bumps the shift.
-- Everything is free in this place: ShopLibrary sets every price to 0, and Robux purchases
-- (whose product ids belong to the original game) are granted without a prompt:
--
--   Data.BuyShopEntryRobux(entryName, isTriple, intendedDay)   shop entries with a ProductID
--   Misc.FreePurchase("Product" | "Gamepass", id)               MonetizationController prompts
--   Misc.FinishPurchasePrompt(success)                           closes the client's prompt state

local ReplicatedStorage = game:GetService("ReplicatedStorage")

local Modules = ReplicatedStorage:WaitForChild("Modules")
local CosmeticLibrary = require(Modules:WaitForChild("CosmeticLibrary"))
local LootLibrary = require(Modules:WaitForChild("LootLibrary"))
local MonetizationLibrary = require(Modules:WaitForChild("MonetizationLibrary"))
local ShopLibrary = require(Modules:WaitForChild("ShopLibrary"))
local ServerOsTime = require(Modules:WaitForChild("ServerOsTime"))

local PlayerDataService = require(script.Parent.PlayerDataService)
local RewardService = require(script.Parent.RewardService)

local Data = ReplicatedStorage:WaitForChild("Remotes"):WaitForChild("Data")
local Misc = ReplicatedStorage:WaitForChild("Remotes"):WaitForChild("Misc")

local DAY = 86400
local DAILY_EMOTES = 4
local MAX_AMOUNT = 10

local ShopService = {}

local function today(): number
	return os.time() // DAY
end

local function secondsToNextDay(): number
	return DAY - os.time() % DAY
end

-- The rotation for one shop day; the same day always gives the same entries.
function ShopService.DailyEntries(shopDay: number)
	local entries = {}
	local random = Random.new(shopDay * 7919 + 17)

	for cosmeticType, stock in ShopLibrary.DailyShopCosmeticTypes or {} do
		local names = table.clone(stock.CosmeticNames or {})
		for index = 1, math.min(DAILY_EMOTES, #names) do
			local name = table.remove(names, random:NextInteger(1, #names))
			local cosmetic = CosmeticLibrary.Cosmetics[name]
			local prices = cosmetic and stock.PricesByRarity and stock.PricesByRarity[cosmetic.Rarity]
			if prices then
				table.insert(entries, {
					EntryName = string.format("daily_%d_%s_%d_%s", shopDay, cosmeticType, index, name),
					EntryType = "Loose",
					Rewards = { { Name = name, Quantity = 1 } },
					Prices = table.clone(prices),
					MainCurrency = next(prices),
					PurchaseStartTime = -1,
					PurchaseDuration = math.huge,
					PurchaseAppearTime = -1,
				})
			end
		end
	end

	return entries
end

local function dailyPayload(player: Player)
	local shift = PlayerDataService.Get(player, "DailyShopSeedShift") or 0
	return {
		Day = today(),
		TimeRemaining = secondsToNextDay(),
		Data = ShopService.DailyEntries(today() + shift),
	}
end

function ShopService.PushDaily(player: Player)
	Data.UpdateDailyShop:FireClient(player, dailyPayload(player))
end

local function findEntry(player: Player, entryName: string, intendedDay: any)
	local entry = ShopLibrary.Entries[entryName]
	if entry then
		return entry
	end

	local shift = PlayerDataService.Get(player, "DailyShopSeedShift") or 0
	if tonumber(intendedDay) ~= today() + shift then
		return nil
	end
	for _, daily in ShopService.DailyEntries(today() + shift) do
		if daily.EntryName == entryName then
			return daily
		end
	end
	return nil
end

local function onSale(entry): boolean
	if (entry.PurchaseStartTime or -1) < 0 then
		return true
	end
	local now = ServerOsTime:Get()
	return now >= entry.PurchaseStartTime and now < entry.PurchaseStartTime + (entry.PurchaseDuration or math.huge)
end

-- Loose cosmetics can be bought once; lootboxes as often as you like.
local function alreadyOwned(player: Player, entry): boolean
	if entry.EntryType == "Lootbox" then
		return false
	end
	local inventory = PlayerDataService.Get(player, "CosmeticInventory")
	for _, reward in entry.Rewards or {} do
		local weapon = reward.Weapon
		if CosmeticLibrary.Cosmetics[reward.Name] then
			local owned
			if weapon == "IsUniversal" then
				owned = CosmeticLibrary:OwnsCosmeticUniversally(inventory, reward.Name)
			elseif weapon == nil or weapon == "IsRandom" then
				owned = CosmeticLibrary:OwnsCosmeticNormally(inventory, reward.Name)
			else
				owned = CosmeticLibrary:OwnsCosmetic(inventory, reward.Name, weapon)
			end
			if not owned then
				return false
			end
		else
			return false
		end
	end
	return true
end

local function buy(player: Player, entryName: any, currency: any, amount: any, intendedDay: any)
	if typeof(entryName) ~= "string" or typeof(currency) ~= "string" then
		return
	end

	local entry = findEntry(player, entryName, intendedDay)
	local price = entry and entry.Prices and entry.Prices[currency]
	if not price or not onSale(entry) or alreadyOwned(player, entry) then
		return
	end

	local count = entry.EntryType == "Lootbox" and math.clamp(math.floor(tonumber(amount) or 1), 1, MAX_AMOUNT) or 1
	local total = price * count
	local balance = tonumber(PlayerDataService.Get(player, currency)) or 0
	if balance < total then
		return
	end

	PlayerDataService.Set(player, currency, balance - total)
	for _ = 1, count do
		RewardService.GrantAll(player, entry.Rewards, true)
	end
end

-- Hands out a shop entry `count` times, if it is on sale and not already owned.
local function grantEntry(player: Player, entry, count: number): boolean
	if not onSale(entry) or alreadyOwned(player, entry) then
		return false
	end
	for _ = 1, count do
		RewardService.GrantAll(player, entry.Rewards, true)
	end
	return true
end

local function buyRobux(player: Player, entryName: any, isTriple: any, intendedDay: any)
	if typeof(entryName) ~= "string" then
		return
	end
	local entry = findEntry(player, entryName, intendedDay)
	if not entry or not entry.ProductID then
		return
	end
	grantEntry(player, entry, (isTriple == true and entry.ProductIDTriple) and 3 or 1)
end

-- Gamepass bundles are claimed once; the rest (products) as often as they are bought.
local function grantBundle(player: Player, bundleName: string): boolean
	local bundle = MonetizationLibrary.Bundles[bundleName]
	if not bundle then
		return false
	end
	if bundle.GamepassName then
		local claimed = PlayerDataService.Get(player, "GamepassBundlesClaimed")
		local passes = PlayerDataService.Get(player, "Gamepasses")
		if not claimed or not passes or claimed[bundle.GamepassName] then
			return false
		end
		passes[bundle.GamepassName] = true
		claimed[bundle.GamepassName] = true
		PlayerDataService.Replicate(player, "Gamepasses")
		PlayerDataService.Replicate(player, "GamepassBundlesClaimed")
	end
	RewardService.GrantAll(player, bundle.Rewards or {}, true)
	return true
end

local function grantProduct(player: Player, productId: number): boolean
	local bundleName = MonetizationLibrary:GetBundleByProductID(productId)
	if bundleName then
		return grantBundle(player, bundleName)
	end

	for _, entry in ShopLibrary.Entries do
		if entry.ProductID == productId or entry.ProductIDTriple == productId then
			return grantEntry(player, entry, entry.ProductIDTriple == productId and 3 or 1)
		end
	end

	local productName = MonetizationLibrary:GetProductName(productId)
	local levels = productName and tonumber(string.match(productName, "^BattlePassLevels(%d+)$"))
	if levels then
		RewardService.GrantAll(player, { { Name = "Season Pass Level", Quantity = levels } }, true)
		return true
	end
	return false
end

local function freePurchase(player: Player, kind: any, id: any)
	local success = false
	if typeof(id) == "number" and PlayerDataService.IsLoaded(player) then
		if kind == "Product" then
			success = grantProduct(player, id)
		elseif kind == "Gamepass" then
			local name = MonetizationLibrary:GetGamepassName(id)
			local pass = name and MonetizationLibrary.Gamepasses[name]
			success = pass ~= nil and grantBundle(player, pass.BundleName)
		end
	end
	Misc.FinishPurchasePrompt:FireClient(player, success)
end

local function refreshDaily(player: Player, intendedDay: any)
	local data = PlayerDataService.Get(player)
	if not data or tonumber(intendedDay) ~= today() + (data.DailyShopSeedShift or 0) then
		return
	end

	local cost = LootLibrary:GetCostToRefreshDailyShop(data.DailyShopRefreshesToday or 0)
	if (data.WeaponKeys or 0) < cost then
		return
	end

	PlayerDataService.Set(player, "WeaponKeys", data.WeaponKeys - cost)
	PlayerDataService.Set(player, "DailyShopRefreshesToday", (data.DailyShopRefreshesToday or 0) + 1)
	PlayerDataService.Set(player, "DailyShopSeedShift", (data.DailyShopSeedShift or 0) + 1)
	ShopService.PushDaily(player)
end

function ShopService.Start()
	Data.RequestDailyShop.OnServerInvoke = dailyPayload
	Data.BuyShopEntry.OnServerEvent:Connect(buy)
	Data.RefreshDailyShop.OnServerEvent:Connect(refreshDaily)
	Data.BuyShopEntryRobux.OnServerEvent:Connect(buyRobux)
	Misc.FreePurchase.OnServerEvent:Connect(freePurchase)
end

ShopService.Remotes = { Data.RequestDailyShop, Data.BuyShopEntry, Data.RefreshDailyShop, Data.BuyShopEntryRobux, Misc.FreePurchase }

return ShopService
