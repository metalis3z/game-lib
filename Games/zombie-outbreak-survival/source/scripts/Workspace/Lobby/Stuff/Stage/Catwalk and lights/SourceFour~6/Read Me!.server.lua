Thanks for using this model!

	
The part called "LengthCompensation" is to help you rotate the lighting
instrument properly to your desired orientation.  It is carefully placed 
so that the natural axis of rotation falls where it's supposed to, on the
pivot points of the yoke of the instrument.

To set rotation, FIRST DO THE VERTICAL AXIS / TILT. If you do the horizontal
axis / pan first, the instrument will not be aligned with the world grid anymore
and you won't be able to tilt the instrument without it getting wonky. Just try
it and you'll see what I mean.

To set the tilt, select the model "TiltMe" under the "PanMe" model and tilt tilt as
desired with the rotate tool. To set the pan, select "PanMe" and again use the
rotate tool.
	
	
	
